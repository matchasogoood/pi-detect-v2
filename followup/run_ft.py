"""run_ft.py : our pipeline with the fine-tuned content scorer (FT-C) and the content block path, on OUR code base.

Adapted from the teammate's run_g.py (written for an older copy of pi_detect_v2).  What is different here:
  * it extends the full H1 baseline list of config.yaml instead of replacing it, so every baseline of the paper is
    in the same run, with the same sessions and the same thresholds;
  * each external score has its own list of modes (h1.ext_modes_by), because PIGuard keeps the mode of the main run
    while FT-C needs both channels (needs the 3-line patch in experiments/h1_behavior_vs_memoryless.py, APPLY_FT.md);
  * seeds come from the command line, never from a hard-coded final list.

Methods added:  B4-OursFT2          the fine-tuned model alone
                full+B4(<mode>)     our pipeline with FT-C as the content score
                full+B5(<mode>)     ... plus the content block path  (= the proposed system)
Training data of FT-C: dev split only (+ Alpaca hard negatives + 600 dev documents with an attack inside).

Usage (pi_detect_v2 folder, its venv active, ft_scorer.py copied next to this file):
  python followup/run_ft.py --smoke
  python followup/run_ft.py --seeds 10 11 12 --out results/dev/ft_dev1/h1     # development run
  python followup/run_ft.py --seeds 20 21 22 23 24 --out results/final_ft/h1        # final run (see PREREG_ft.md)
"""
from __future__ import annotations

import argparse
import dataclasses
import importlib.util
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

CONTENT_PATH_FPR_SHARE = 0.5       # tau_ft may use at most this share of the session FPR target (as in G)
OURS_FPR_SCALE = 1.0               # validation FPR target of full+B4/B5 = scale * 5%; set by --ours-fpr-scale (PREREG_ft.md, addendum)
MODES_BY = {"B3b": ["ind_win_logit_only"],                 # unchanged from the main run
            "B4": ["ext"],
            "B5": ["ext", "ext_win_logit"]}                # B5 = B4 + block path; two read-outs, chosen on dev seeds only


def make_config(seeds, tt_rows=None, bipia_tasks=None) -> Path:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    if seeds:
        cfg["seeds"] = list(seeds)
    if tt_rows:
        cfg["data"]["tasktracker_max_rows"] = int(tt_rows)         # 8000 = every row that was built
    if bipia_tasks:
        cfg["data"]["bipia_tasks"] = list(bipia_tasks)
    cfg["data"]["dedup"] = True            # de-duplicated splits + leak gate (PREREG_ft.md)
    h = cfg["h1"]
    h["baselines"] = list(dict.fromkeys(list(h.get("baselines", [])) + ["B4"]))
    h["ext_content"] = list(dict.fromkeys(list(h.get("ext_content", [])) + ["B4", "B5"]))
    base_modes = h.get("ext_modes", ["ext", "fused"])
    h["ext_modes_by"] = {n: MODES_BY.get(n, base_modes) for n in h["ext_content"]}
    for k in ("raw_dir", "local_dir"):
        p = Path(cfg["data"][k])
        cfg["data"][k] = str(p if p.is_absolute() else (ROOT / p).resolve())
    out = HERE / "config_ft.yaml"
    out.write_text("# generated by followup/run_ft.py from ../config.yaml -- do not edit by hand\n"
                   + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return out


class ContentPath:
    """Wraps a fitted Stage 2: an event whose content-model score is above tau goes through the fast path."""

    def __init__(self, inner, scorer, tau: float):
        object.__setattr__(self, "_inner", inner)
        object.__setattr__(self, "_scorer", scorer)
        object.__setattr__(self, "_tau", float(tau))

    def process(self, text, channel):
        out = self._inner.process(text, channel)
        if not out.fast and not out.hard and float(self._scorer.score([text])[0]) > self._tau:
            return dataclasses.replace(out, fast=True)       # a copy: never mutate a cached Stage 2 result
        return out

    def __getattr__(self, k):
        return getattr(self._inner, k)

    def __setattr__(self, k, v):
        setattr(self._inner, k, v)       # e.g. measure_cost swaps det.s2.emb: it must reach the real Stage 2


def load_h1():
    spec = importlib.util.spec_from_file_location("h1mod", ROOT / "experiments" / "h1_behavior_vs_memoryless.py")
    h1 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(h1)
    return h1


def install(h1, fpr_target: float):
    from ft_scorer import FineTunedMiniLM
    from pidetect.attackbank import HAND_ATTACKS
    from pidetect.baselines import ScoreBaseline
    from pidetect.metrics import threshold_for_fpr
    from pidetect.runtime import log

    ft = FineTunedMiniLM(inject=True, name="B4-OursFT2")

    class WithPath(ScoreBaseline):                     # same model; marks "use the content block path"
        name = "B5-OursFT2path"

        def score(self, texts, fresh=False):
            return ft.score(texts, fresh=fresh)

        def score_fresh(self, texts):
            return ft.score(texts, fresh=True)

    b5 = WithPath()
    taus = {}
    orig_bb, orig_bfs, orig_cost = h1.build_baselines, h1.build_full_system, h1.measure_cost

    def build_baselines(cfg, emb, names, skip=()):
        names = list(names)
        extra = {"B4": ft, "B5": b5}
        built = orig_bb(cfg, emb, [n for n in names if n not in extra], skip)
        for n in names:
            if n in extra and n not in set(skip):
                built[extra[n].name] = extra[n]
        return built

    def tau_for_seed(cfg, sp, seed):
        if seed not in taus:
            sess = h1.h1_sessions(sp, "val", seed, cfg["h1"]["n_test_per_kind"])
            maxes = [max(ft.score([e.text for e in s.events])) for s in sess if not s.is_attack]
            target = cfg["h1"]["target_session_fpr"] * OURS_FPR_SCALE * CONTENT_PATH_FPR_SHARE
            taus[seed] = dict(tau_ft=float(threshold_for_fpr(maxes, target)), target=target,
                              n_benign_val_sessions=len(maxes))
            log(f"[FT] seed {seed}: content block path tau_ft={taus[seed]['tau_ft']:.4f} "
                f"(<= {target:.3f} of {len(maxes)} benign val sessions)")
        return taus[seed]["tau_ft"]

    def build_full_system(cfg, world, emb, seed, ext=None, **kw):
        res = orig_bfs(cfg, world, emb, seed, ext=ext, **kw)
        if ext is None and ft.seed != seed:             # first build of a seed: train FT-C on its dev split
            ft.fit_for_seed(seed, res[1], HAND_ATTACKS)
        if ext is not None and getattr(ext, "bl", None) is b5:
            det = res[0]
            det.s2 = ContentPath(det.s2, ft, tau_for_seed(cfg, res[1], seed))
        return res

    def measure_cost(det, sessions, n_events=100):
        ft.no_cache = True                               # time the content model too: score every event fresh
        try:
            return orig_cost(det, sessions, n_events)
        finally:
            ft.no_cache = False

    orig_cal = h1.calibrate_session_threshold

    def calibrate(det, benign_val, target, *args, **kw):
        if OURS_FPR_SCALE != 1.0 and str(det.name).startswith(("full+B4", "full+B5")):
            target = target * OURS_FPR_SCALE            # stricter validation target for the FT-C systems only
        return orig_cal(det, benign_val, target, *args, **kw)

    h1.calibrate_session_threshold = calibrate
    h1.build_baselines, h1.build_full_system, h1.measure_cost = build_baselines, build_full_system, measure_cost
    return ft, taus


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--seeds", type=int, nargs="*", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--ours-fpr-scale", type=float, default=1.0)
    ap.add_argument("--tasktracker-rows", type=int, default=None)
    ap.add_argument("--bipia-tasks", nargs="*", default=None)
    a, rest = ap.parse_known_args()
    out = Path(a.out) if a.out else ROOT / "results" / ("smoke" if a.smoke else "dev") / "ft_run" / "h1"
    out = out if out.is_absolute() else ROOT / out
    out.mkdir(parents=True, exist_ok=True)
    global OURS_FPR_SCALE
    OURS_FPR_SCALE = a.ours_fpr_scale
    cfg_path = make_config(a.seeds, a.tasktracker_rows, a.bipia_tasks)
    far = yaml.safe_load(cfg_path.read_text(encoding="utf-8"))["h1"]["target_session_fpr"]
    h1 = load_h1()
    ft, taus = install(h1, far)
    sys.argv = ["h1", "--config", str(cfg_path), "--out", str(out)] + (["--smoke"] if a.smoke else []) + rest
    rc = h1.main()
    (out / "ft_train_info.json").write_text(json.dumps(ft.train_info, indent=1))
    (out / "content_path_thresholds.json").write_text(json.dumps(taus, indent=1))
    print(f"\nresults in {out}")
    if not a.smoke:  # post-run figure only; reads the saved CSVs, changes nothing in the run
        sys.path.insert(0, str(ROOT))
        from pidetect.roc_plot import auto_figures
        auto_figures(out)
    return rc


if __name__ == "__main__":
    sys.exit(main() or 0)
